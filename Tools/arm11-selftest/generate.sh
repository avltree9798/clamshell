#!/bin/sh
# Rebuilds SelfTestImage.swift from selftest.c. Needs clang and lld (LLVM 15 or later).
set -eu
cd "$(dirname "$0")"
out=$(mktemp -d)
clang --target=armv6k-none-eabi -marm -mfloat-abi=hard -mfpu=vfpv2 -O2 -ffreestanding -fno-math-errno \
    -nostdlib -c selftest.c -o "$out/guest.o"
ld.lld -N -Ttext=0x1000 --entry=_start "$out/guest.o" -o "$out/guest.elf"
llvm-objcopy -O binary "$out/guest.elf" "$out/guest.bin"
results=$(llvm-nm "$out/guest.elf" | awk '$3 == "results" { print $1 }')
entry=$(llvm-nm "$out/guest.elf" | awk '$3 == "_start" { print $1 }')
clang -O2 -fno-math-errno -ffp-contract=off -Dmain=guest_main -c selftest.c -o "$out/host-selftest.o"
clang -O2 host.c "$out/host-selftest.o" -o "$out/host"
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Generated by Tools/arm11-selftest/generate.sh from selftest.c. Do not edit."
    echo
    echo "enum SelfTestImage {"
    echo "    static let loadAddress: UInt32 = 0x1000"
    echo "    static let entry: UInt32 = 0x$entry"
    echo "    static let resultsAddress: UInt32 = 0x$results"
    echo "    static let bytes: [UInt8] = ["
    od -An -v -tx1 "$out/guest.bin" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/       /; s/, *$/,/'
    echo "    ]"
    echo "    static let expected: [UInt32] = ["
    "$out/host" | sed '/^$/d; s/^/        /'
    echo "    ]"
    echo "}"
} > ../../Tests/ARMCoreTests/SelfTestImage.swift
rm -rf "$out"

#!/bin/sh
# Builds hello.3dsx and regenerates the test image. Needs clang and lld.
set -eu
cd "$(dirname "$0")"
out=$(mktemp -d)
clang --target=armv6k-none-eabi -marm -mfloat-abi=hard -mfpu=vfpv2 -O2 -ffreestanding -nostdlib \
    -fno-builtin -c hello.c -o "$out/hello.o"
ld.lld -N -T link.ld "$out/hello.o" -o "$out/hello.elf"
python3 pack3dsx.py "$out/hello.elf" "$out/hello.3dsx"
report=$(llvm-nm "$out/hello.elf" | awk '$3 == "report" { print $1 }')
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Generated by Tools/ctr-hello/build.sh from hello.c. Do not edit."
    echo
    echo "enum HelloImage {"
    echo "    static let reportAddress: UInt32 = 0x$report"
    echo "    static let bytes: [UInt8] = ["
    od -An -v -tx1 "$out/hello.3dsx" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/       /; s/, *$/,/'
    echo "    ]"
    echo "}"
} > ../../Tests/CTRCoreTests/HelloImage.swift
rm -rf "$out"
